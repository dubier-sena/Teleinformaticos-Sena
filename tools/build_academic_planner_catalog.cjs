'use strict';
// Read-only extraction from local declarations. Does not execute authentication.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const crypto = require('node:crypto');
const root = path.resolve(__dirname,'..');
function build() {
  const auth = fs.readFileSync(path.join(root,'js/portal_auth.js'),'utf8');
  const declaration = fs.readFileSync(path.join(root,'js/guide_declarations.js'),'utf8');
  const match = auth.match(/const FICHA_MAP = (\{[\s\S]*?\n  \});/);
  if (!match) throw new Error('No se encontró el mapa literal de fichas.');
  const map = vm.runInNewContext('(' + match[1] + ')',{}, {timeout:1000});
  const registered = [];
  vm.runInNewContext(declaration,{window:{ActivityStandard:{registerGuide:g=>registered.push(g)}}},{timeout:1000});
  const norm = s => String(s).normalize('NFD').replace(/[\u0300-\u036f]/g,'').toLowerCase().replace(/[.,]/g,'').replace(/\s+/g,' ').trim();
  const names = new Map();
  registered.forEach(g => {const code = String(g.competencia).match(/^\d{9}/)?.[0]; if(code) {if(!names.has(code))names.set(code,new Set());names.get(code).add(norm(g.competencia));}});
  const fichas = Object.entries(map).map(([id,f]) => ({id,institutionId:f.inst.includes('Kennedy')?'john-f-kennedy':'santa-barbara',grade:f.grupo,program:'Sistemas Teleinformaticos',guideFiles:f.guias}));
  const items = [], unresolved = [];
  fichas.forEach(f => {
    const grouped = new Map();
    registered.filter(g=>g.files.some(file=>f.guideFiles.includes(file))).forEach(g=>{
      const code = String(g.competencia).match(/^\d{9}/)?.[0];
      const order = Number(String(g.resultado).match(/^RAP\s*0*(\d+)/i)?.[1]);
      if(!code || !order) {unresolved.push({ficha:f.id,guide:g.guideTitle,reason:'Sin código de competencia o RAP numerado; no se programa como RAP.'});return;}
      const id = f.id + ':' + code + ':' + order;
      let item = grouped.get(id);
      if(!item) {item={id,program:g.program,competencyCode:code,competency:g.competencia,rap:g.resultado,order,fichas:[f.id],source:'js/guide_declarations.js',needsVerification:names.get(code).size>1,guides:[]};grouped.set(id,item);}
      if(norm(item.rap)!==norm(g.resultado)) item.needsVerification=true;
      g.files.filter(file=>f.guideFiles.includes(file)).forEach(file=> item.guides.push({file,title:g.guideTitle,activities:g.activities.map(a=>({id:a.id,label:a.label}))}));
    });
    items.push(...grouped.values());
  });
  return {schemaVersion:1,sourceHashes:{'js/portal_auth.js':crypto.createHash('sha256').update(auth).digest('hex'),'js/guide_declarations.js':crypto.createHash('sha256').update(declaration).digest('hex')},notice:'Fuente: declaraciones del portal; no certifica catálogo curricular completo ni intensidades. Cotejo oficial pendiente. Las discrepancias se bloquean.',fichas,items,unresolved};
}
function output(data) {return '/* Generated by tools/build_academic_planner_catalog.cjs; no learner data. */\n(function(root){\n  const catalog = '+JSON.stringify(data,null,2)+';\n  if(typeof module === "object" && module.exports) module.exports=catalog;\n  else root.academicPlannerCatalog=catalog;\n})(typeof self !== "undefined" ? self : this);\n';}
if(require.main===module) {
  const target=path.join(root,'data/academic_planner_catalog.js'), text=output(build());
  if(process.argv.includes('--check')) {if(fs.readFileSync(target,'utf8')!==text) throw new Error('Catálogo desactualizado. Ejecute el generador.');}
  else fs.writeFileSync(target,text);
}
module.exports={build,output};
